#!/usr/bin/env node
/**
 * Post-build: write dist/_redirects (Cloudflare Workers Static Assets format).
 *
 * Story URLs depend on the template (/article/<slug> for news, /opinion/<slug> for opinion), so
 * flipping a story's template would 404 every old link. For every story this emits a 301 from the
 * *other* prefix to the live one. Static rules from public/_redirects are kept first.
 *
 * Usage: node scripts/generate-redirects.mjs   (after `astro build`)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
export const ROOT_DIR = path.resolve(path.dirname(__filename), '..');

const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

function walkMetaFiles(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  const entries = fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walkMetaFiles(full, acc);
    else if (entry.isFile() && entry.name === 'meta.json') acc.push(full);
  }
  return acc;
}

/** Live path for a story, mirroring getArticleHref() in src/loaders/articles.ts. */
export function storyPath(meta) {
  return meta.template === 'opinion' ? `/opinion/${meta.slug}` : `/article/${meta.slug}`;
}

/** The prefix a story would have had under the other template. */
export function alternatePath(meta) {
  return meta.template === 'opinion' ? `/article/${meta.slug}` : `/opinion/${meta.slug}`;
}

/**
 * Build redirect lines for a list of story metas. Pure: no filesystem access.
 * Retracted stories keep their tombstone URL, so they get the same alias redirect.
 */
export function buildStoryRedirects(metas) {
  const live = new Set(metas.map(storyPath));
  const lines = [];
  for (const meta of [...metas].sort((a, b) => a.slug.localeCompare(b.slug))) {
    if (!meta || typeof meta.slug !== 'string' || !SLUG_RE.test(meta.slug)) {
      throw new Error(`generate-redirects: invalid slug ${JSON.stringify(meta?.slug)}`);
    }
    const from = alternatePath(meta);
    // Never shadow a page that really exists at that path
    if (live.has(from)) continue;
    lines.push(`${from} ${storyPath(meta)} 301`);
  }
  return lines;
}

export function readStaticRules(publicFile) {
  if (!fs.existsSync(publicFile)) return [];
  return fs
    .readFileSync(publicFile, 'utf8')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#'));
}

export function generateRedirects({
  contentDir = path.join(ROOT_DIR, 'content', 'articles'),
  publicFile = path.join(ROOT_DIR, 'public', '_redirects'),
  outFile = path.join(ROOT_DIR, 'dist', '_redirects'),
} = {}) {
  const metas = walkMetaFiles(contentDir).map((file) => JSON.parse(fs.readFileSync(file, 'utf8')));
  const staticRules = readStaticRules(publicFile);
  const storyRules = buildStoryRedirects(metas);
  const body = [
    '# Generated by scripts/generate-redirects.mjs. Do not edit dist/_redirects by hand.',
    ...staticRules,
    '# Template aliases: /article/<slug> <-> /opinion/<slug>',
    ...storyRules,
    '',
  ].join('\n');
  // Cloudflare limits: 2,000 static + 100 dynamic rules
  if (staticRules.length + storyRules.length > 2000) {
    throw new Error(`generate-redirects: ${staticRules.length + storyRules.length} rules exceeds the 2,000 static rule limit`);
  }
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, body);
  return { outFile, staticRules: staticRules.length, storyRules: storyRules.length };
}

const isMain = typeof process.argv[1] === 'string' && path.resolve(process.argv[1]) === __filename;
if (isMain) {
  const result = generateRedirects();
  console.log(
    `[redirects] Wrote ${path.relative(ROOT_DIR, result.outFile)} (${result.staticRules} static + ${result.storyRules} story aliases)`
  );
}
